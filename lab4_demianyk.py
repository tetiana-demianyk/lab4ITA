import cv2
import easyocr
import matplotlib.pyplot as plt
import numpy as np
import os

# Створюємо OCR-розпізнавач для української та англійської мов
reader = easyocr.Reader(['uk', 'en'], gpu=False)

# Назви завантажених зображень
image_names = list(uploaded.keys())

# Розпізнаємо текст на кожному зображенні
for image_name in image_names:
    image = cv2.imread(image_name)

    print("\nФайл:", image_name)

    results = reader.readtext(image)

    recognized_text = " ".join([result[1] for result in results])

    print("Розпізнаний текст:")
    print(recognized_text)

    # Показуємо зображення
    plt.figure(figsize=(10, 6))
    plt.imshow(cv2.cvtColor(image, cv2.COLOR_BGR2RGB))
    plt.title(image_name)
    plt.axis("off")
    plt.show()

import pandas as pd

# Кути повороту за 4 варіантом
angles = [0, -1, -3, -5, -7, -9, -11, -13, -15]

experiment_results = []

for image_name in image_names:
    image = cv2.imread(image_name)
    height, width = image.shape[:2]

    print("\nФайл:", image_name)

    for angle in angles:
        # Повертаємо зображення
        center = (width // 2, height // 2)
        matrix = cv2.getRotationMatrix2D(center, angle, 1.0)

        rotated = cv2.warpAffine(
            image,
            matrix,
            (width, height),
            borderMode=cv2.BORDER_REPLICATE
        )

        # Розпізнаємо текст
        results = reader.readtext(rotated)
        text_result = " ".join([item[1] for item in results])

        experiment_results.append({
            "Файл": image_name,
            "Кут повороту": angle,
            "Кількість розпізнаних фрагментів": len(results),
            "Розпізнаний текст": text_result
        })

# Формуємо таблицю результатів
df = pd.DataFrame(experiment_results)

display(df)

confidence_results = []

for image_name in image_names:
    image = cv2.imread(image_name)
    height, width = image.shape[:2]
    center = (width // 2, height // 2)

    for angle in angles:
        matrix = cv2.getRotationMatrix2D(center, angle, 1.0)

        rotated = cv2.warpAffine(
            image, matrix, (width, height),
            borderMode=cv2.BORDER_REPLICATE
        )

        results = reader.readtext(rotated)

        text_result = " ".join([item[1] for item in results])

        if results:
            avg_confidence = np.mean([item[2] for item in results])
        else:
            avg_confidence = 0

        confidence_results.append({
            "Файл": image_name,
            "Кут": angle,
            "Кількість фрагментів": len(results),
            "Кількість символів": len(text_result),
            "Середня впевненість (%)": round(avg_confidence * 100, 2)
        })

confidence_df = pd.DataFrame(confidence_results)
display(confidence_df)

plt.figure(figsize=(9, 5))

for image_name in confidence_df["Файл"].unique():
    data = confidence_df[confidence_df["Файл"] == image_name]

    plt.plot(
        data["Кут"],
        data["Середня впевненість (%)"],
        marker="o",
        label=image_name
    )

plt.title("Вплив кута повороту на впевненість OCR")
plt.xlabel("Кут повороту (градуси)")
plt.ylabel("Середня впевненість (%)")
plt.grid(True)
plt.legend()
plt.show()

